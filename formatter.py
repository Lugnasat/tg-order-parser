# ---------------------------------------------
# FORMATTER — сборка текста уведомления в личку бота (HTML)
# Перенос стиля lead-сообщения образца. Отличия:
#   - кликабельная ссылка на исходный пост (<a href>);
#   - текст заказа ЭКРАНИРУЕМ (html.escape) — при parse_mode=HTML символы
#     < > & в чужом посте иначе сломали бы разметку (у образца — латентный баг);
#   - показываем найденную КАТЕГОРИЮ (чтобы на глаз судить релевантность/точность);
#   - текст заказа режем до фрагмента, всё сообщение держим <= лимита Telegram 4096.
# ---------------------------------------------

import html

# жёсткий лимит Telegram на сообщение
TELEGRAM_MAX_LEN: int = 4096

# сколько символов исходного текста показываем (фрагмента хватает для оценки;
# держит итог заведомо ниже 4096 при любом размере поста)
FRAGMENT_CHARS: int = 1000


# -------------------------
# FORMAT_MESSAGE — готовый HTML-текст уведомления
# -------------------------
def format_message(category: str, text: str, link: str) -> str:
    # режем исходный текст до фрагмента ДО экранирования
    fragment = text.strip()

    if len(fragment) > FRAGMENT_CHARS:
        fragment = fragment[:FRAGMENT_CHARS].rstrip() + "…"

    # экранируем фрагмент (защита HTML-разметки)
    safe_fragment = html.escape(fragment)

    message = (
        "🔥 Новый заказ\n"
        f"🏷 Категория: {category}\n\n"
        f"💬 {safe_fragment}\n\n"
        f'🔗 <a href="{link}">Открыть сообщение</a>'
    )

    # подстраховка: ничего не должно превышать лимит (фрагмент уже ограничен)
    if len(message) > TELEGRAM_MAX_LEN:
        message = message[:TELEGRAM_MAX_LEN]

    return message
