# -------------------------
# VERDICT — точная копия порядка решений из collector.process_message
# -------------------------
def verdict(text: str) -> tuple[str, str]:
    if has_minus(text):
        return "cut", "minus"

    category = extract_category(text)
    if category is None:
        return "cut", "no-cat"

    return "pass", category


# -------------------------
# MAIN — прогон + сводка отклонений от ожидаемого
# -------------------------
def main() -> None:
    ok = 0
    fails: list[str] = []

    print(f"{'#':>2}  {'ОЖИД':<5} {'ФАКТ':<5} {'ПОЧЕМУ':<10} ЗАМЕТКА")
    print("-" * 78)

    for fid, expected, note, text in FIXTURES:
        got, why = verdict(text)
        mark = "OK " if got == expected else "!! "

        if got == expected:
            ok += 1
        else:
            fails.append(f"#{fid}: ожидали {expected}, получили {got} ({why}) — {note}")

        print(f"{fid:>2}  {expected:<5} {got:<5} {why:<10} {mark}{note}")

    print("-" * 78)
    print(f"Совпало: {ok}/{len(FIXTURES)}")

    if fails:
        print("\nОТКЛОНЕНИЯ:")
        for f in fails:
            print(" -", f)


if __name__ == "__main__":
    main()
