# -------------------------
# TEST_1_FINGERPRINTS — внутри группы один отпечаток; между группами разные
# -------------------------
def test_1_fingerprints() -> bool:
    print("ТЕСТ 1 — отпечатки")
    print("-" * 70)

    group_fps: list[tuple[str, str]] = []
    ok = True

    for name, variants in GROUPS:
        fps = {fingerprint(v) for v in variants}

        collapsed = len(fps) == 1
        ok = ok and collapsed
        mark = "OK " if collapsed else "!! "

        print(f"{mark}«{name}»: {len(variants)} вариантов -> {len(fps)} отпечатк(ов) "
              f"(ждём 1)")

        # берём любой отпечаток группы для проверки межгрупповой уникальности
        group_fps.append((name, next(iter(fps))))

    # межгрупповая уникальность — разные заказы НЕ должны схлопнуться
    distinct = len({fp for _, fp in group_fps}) == len(group_fps)
    ok = ok and distinct
    mark = "OK " if distinct else "!! "
    print(f"{mark}межгрупповая уникальность: {len(group_fps)} групп -> "
          f"{len({fp for _, fp in group_fps})} разных отпечатков (ждём {len(group_fps)})")

    return ok


# -------------------------
# TEST_2_THROUGH_DB — прогон потока через is_duplicate на in-memory БД.
# Каждому варианту даём СВОИ chat_id/message_id/author_id (разные каналы и
# боты) — проверяем, что cross-chat дедуп ловит дубль и без них.
# -------------------------
def test_2_through_db() -> bool:
    print("\nТЕСТ 2 — сквозь БД (cross-chat, разные канал/автор)")
    print("-" * 70)

    conn = db.connect(":memory:")
    db.init(conn)

    passed = 0      # сколько «уникальных» прошло дедуп
    msg_id = 0

    for name, variants in GROUPS:
        for variant_idx, text in enumerate(variants):
            msg_id += 1
            fp = fingerprint(text)

            # разные «каналы» и разные боты-постеры на каждый вариант —
            # cross-chat дедуп должен поймать дубль и без их совпадения
            chat_id = -1000 - variant_idx
            author_id = 5000 + variant_idx

            if not db.is_duplicate(conn, fp, chat_id, msg_id, author_id):
                passed += 1
                db.mark_seen(conn, fp, chat_id, msg_id, author_id)

    total_msgs = sum(len(v) for _, v in GROUPS)
    expected = len(GROUPS)
    ok = passed == expected
    mark = "OK " if ok else "!! "

    print(f"{mark}на вход {total_msgs} сообщений ({len(GROUPS)} заказа x3 канала) "
          f"-> прошло {passed} (ждём {expected})")

    conn.close()
    return ok


# -------------------------
# MAIN — оба теста + итог
# -------------------------
def main() -> None:
    ok1 = test_1_fingerprints()
    ok2 = test_2_through_db()

    print("\n" + "=" * 70)
    if ok1 and ok2:
        print("ИТОГ: оба теста зелёные — кросс-канальные дубли схлопываются, "
              "разные заказы проходят.")
    else:
        print("ИТОГ: ЕСТЬ ОТКЛОНЕНИЯ — см. строки с !! выше.")


if __name__ == "__main__":
    main()
