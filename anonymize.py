# ---------------------------------------------
# ANONYMIZE — обезличивание текста заявки ДО показа на витрине сайта.
#
# ЗАКОН модуля экспорта (спека `парсер-экспорт-на-сайт` §2, §8): ни один
# контакт, @ник, ссылка или название источника/чата НЕ должен попасть в
# обезличенный сниппет. Принцип — «при сомнении режем»: лучше выкинуть кусок
# текста, чем пропустить PII наружу.
#
# Чистая функция (без секретов и сети) — гоняется offline тестом
# anonymize_check.py на реальных заявках. Порядок шагов важен:
# сначала структурные блоки (markdown-ссылки, URL, e-mail), потом @ники и
# телефоны, потом хвосты площадок (Автор/Проект/Бюджет/Kwork/разделители),
# в конце — финальная подстраховка-зачистка и схлопывание пробелов.
# ---------------------------------------------

import re

# сколько символов очищенного текста кладём в сниппет (с запасом; сайт всё
# равно режет до 120 — спека §6). Обрезаем по границе, добавляя многоточие.
SNIPPET_MAX_CHARS: int = 200


# -------------------------
# РЕГУЛЯРКИ — компилируем один раз на уровне модуля.
# str по умолчанию в Unicode-режиме: \w ловит и кириллицу (нужно для @ников
# и слов вроде «Автор»).
# -------------------------

# markdown-ссылка [видимый текст](url) -> оставляем только видимый текст
_RE_MD_LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")

# голые ссылки: http(s)://… , www.… , t.me/… (и без схемы) — вырезаем целиком
_RE_URL = re.compile(r"(?:https?://|www\.|t\.me/)\S+", re.IGNORECASE)

# e-mail — до @ников (у e-mail в домене есть точка, отличаем по ней)
_RE_EMAIL = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")

# @ник телеграма/площадки — латиница/кириллица/цифры/подчёркивание
_RE_NICK = re.compile(r"@\w+")

# хвосты площадок построчно: «Автор: …», «Проект: …», строки бюджета/оплаты,
# футер Kwork. (?im): i — регистр, m — ^/$ по строкам.
_RE_TAIL_LINES = re.compile(
    r"(?im)^.*(?:автор\s*:|проект\s*:|бюджет|₽|оплата\s+на\s+любую|"
    r"не\s+указан|kwork).*$"
)

# визуальные разделители каналов: =====, ----, волны 〰️
_RE_SEPARATORS = re.compile(r"={3,}|-{3,}|〰️+")

# хэштеги-футеры (#верстка, #скрипты_боты_miniapp) — шум площадки
_RE_HASHTAG = re.compile(r"#\w+")

# декоративные эмодзи-префиксы постов (✅📌📝💳🌐🔥🏷💬🔗🤖) — убираем
_RE_DECOR = re.compile(r"[✅📌📝💳🌐🔥🏷💬🔗🤖]")

# схлопывание любых пробельных последовательностей (вкл. переводы строк)
_RE_WS = re.compile(r"\s+")


# -------------------------
# _STRIP_PHONES — вырезать последовательности с 7+ цифрами (телефоны, id).
# Цифры могут идти с разделителями +, пробел, скобки, дефис, точка. Считаем
# именно ЦИФРЫ (≥7) — так одиночные числа описания («2 недели», «5к») целы,
# а телефон/длинный id режется. Реализуем через функцию-замену, чтобы
# проверять количество цифр в найденном куске.
# -------------------------
_RE_DIGIT_RUN = re.compile(r"\+?\d[\d\s().\-]{5,}\d")


def _strip_phones(text: str) -> str:
    def _cut(match: re.Match) -> str:
        digits = sum(ch.isdigit() for ch in match.group(0))
        # 7+ цифр в одной группе -> похоже на телефон/длинный id -> режем
        return " " if digits >= 7 else match.group(0)

    return _RE_DIGIT_RUN.sub(_cut, text)


# -------------------------
# ANONYMIZE — главный вход: сырой текст заявки -> безопасный сниппет.
# -------------------------
def anonymize(text: str) -> str:
    if not text:
        return ""

    # 1) markdown-ссылки -> только видимый текст (URL внутри убираем)
    text = _RE_MD_LINK.sub(r"\1", text)

    # 2) голые ссылки целиком
    text = _RE_URL.sub(" ", text)

    # 3) e-mail (до @ников — у почты домен с точкой)
    text = _RE_EMAIL.sub(" ", text)

    # 4) @ники
    text = _RE_NICK.sub(" ", text)

    # 5) телефоны и длинные id (7+ цифр)
    text = _strip_phones(text)

    # 6) хвосты площадок построчно (Автор/Проект/Бюджет/Оплата/Kwork)
    text = _RE_TAIL_LINES.sub(" ", text)

    # 7) разделители, хэштеги, декоративные эмодзи
    text = _RE_SEPARATORS.sub(" ", text)
    text = _RE_HASHTAG.sub(" ", text)
    text = _RE_DECOR.sub(" ", text)

    # 8) ФИНАЛЬНАЯ ПОДСТРАХОВКА (закон «0 утечек»): если что-то структурное
    #    уцелело после шагов выше — добиваем грубой зачисткой остатков
    #    @… и http… токенов. Дешевле перестраховаться, чем пропустить PII.
    text = re.sub(r"\S*@\S*", " ", text)
    text = re.sub(r"\S*(?:https?|t\.me|www\.)\S*", " ", text, flags=re.IGNORECASE)

    # 9) схлопнуть пробелы и обрезать до сниппета
    text = _RE_WS.sub(" ", text).strip()

    if len(text) > SNIPPET_MAX_CHARS:
        text = text[:SNIPPET_MAX_CHARS].rstrip() + "…"

    return text
