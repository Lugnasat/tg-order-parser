# ---------------------------------------------
# FINGERPRINT — канонический отпечаток заказа для кросс-канального дедупа.
#
# v1 брал md5(text.lower().strip()) — почти сырой текст. Один заказ из
# разных каналов приходит с разным обрамлением (эмодзи-префиксы ✅/📌/📝,
# служебный хвост «Бюджет/Автор/🤖 Kwork Бот», разделители ===== / 〰️) →
# три разных текста → три разных md5 → дубли текли.
#
# v2: срезаем хвост-обрамление канала, сильно нормализуем тело, отпечаток
# берём по чистому телу — он одинаков для одного заказа из ЛЮБОГО канала.
# Подробный диагноз — спека freelance-lead-parser-v2.md §1.2.
# ---------------------------------------------

import hashlib

# нормализацию переиспользуем из matching (lower, ё→е, убрать пунктуацию/
# эмодзи, схлопнуть пробелы) — не плодим вторую копию той же логики
from matching import normalize


# -------------------------
# TAIL_SEPARATORS — разделители, которыми каналы отбивают служебный хвост
# (бюджет/автор/хэштеги) от тела заказа. В живом тексте заказа НЕ
# встречаются, поэтому срез по ним консервативен — само тело не задевает.
# Тюнимый параметр: новый канал с другим разделителем — добавить сюда.
# -------------------------
TAIL_SEPARATORS: tuple[str, ...] = (
    "=====",   # kwork_market: «=============»
    "〰",       # freelance_zakazy: «〰️〰️〰️〰️»
)


# -------------------------
# STRIP_CHANNEL_TAIL — отрезать всё от первого служебного разделителя
# -------------------------
def _strip_channel_tail(text: str) -> str:
    cut = len(text)

    for sep in TAIL_SEPARATORS:
        pos = text.find(sep)
        if pos != -1:
            cut = min(cut, pos)

    return text[:cut]


# -------------------------
# FINGERPRINT — одинаков для одного заказа из любого канала
# -------------------------
def fingerprint(text: str) -> str:
    # 1) снять служебный хвост канала (бюджет/автор/хэштеги)
    body = _strip_channel_tail(text)

    # 2) сильная нормализация: эмодзи-префиксы ✅/📌/📝 уйдут как пунктуация
    body = normalize(body)

    # 3) md5 по чистому телу
    return hashlib.md5(body.encode()).hexdigest()
